#!/usr/bin/env node
/**
 * generate-env-manifest.js — works out which environment variables each
 * backend service actually reads.
 *
 * Why this exists: boot-all.js spawns every service with `...process.env`, so
 * all 39 inherit every secret on the platform. autocomplete-service reads 7
 * variables and receives hundreds, including the keys that protect bank
 * accounts and taxpayer identification numbers. Nothing decided that; it is
 * what `spawn` does by default.
 *
 * This scans each service for the variables it reads and writes
 * env-manifest.json, which boot-all.js uses to hand each child only what it
 * needs.
 *
 * Usage:
 *   node scripts/generate-env-manifest.js          # rewrite env-manifest.json
 *   node scripts/generate-env-manifest.js --check  # fail if it is out of date
 *
 * A static scan cannot see a name built at runtime, for example
 * `get(`${prefix}_${kid}`)` in payout-service's key ring. Those go in
 * `extra` in the manifest by hand and survive regeneration; this script never
 * removes them. That is also why the manifest ships in monitor mode: it
 * reports what it would withhold for a while before it withholds anything.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const BACKEND = path.resolve(__dirname, '..');
const APPS = path.join(BACKEND, 'apps');
const LIBS = path.join(BACKEND, 'libs');
const OUT = path.join(BACKEND, 'env-manifest.json');

const SKIP_DIRS = new Set(['node_modules', 'dist', 'build', '.next', 'coverage', 'test']);
const CODE = /\.(ts|js|mjs|cjs)$/;
const IS_SPEC = /\.(spec|test|e2e-spec)\.(ts|js)$/;

/** Names that look like variables but are not, or are noise from type positions. */
const NOT_A_VAR = new Set([
  'NODE_ENV', // added by the baseline, not per service
  'PORT',
  'HOST',
]);

const PATTERNS = [
  // process.env.FOO
  /process\.env\.([A-Z][A-Z0-9_]{2,})/g,
  // process.env['FOO'] and process.env["FOO"]
  /process\.env\[\s*['"]([A-Z][A-Z0-9_]{2,})['"]\s*\]/g,
  // config.get('FOO'), configService.get<string>('FOO', 'default'), this.config.get(...)
  /\.get(?:<[^>]*>)?\(\s*['"]([A-Z][A-Z0-9_]{2,})['"]/g,
  // configService.getOrThrow('FOO')
  /\.getOrThrow(?:<[^>]*>)?\(\s*['"]([A-Z][A-Z0-9_]{2,})['"]/g,
  // A bare get('FOO'), from a local helper rather than a method. The gateway's
  // rate limiter does this: `const get = (key) => config.get(key)`, and the
  // first version of this scanner missed every RATE_LIMIT_* variable because
  // it required a dot.
  /(?:^|[^.\w])get(?:<[^>]*>)?\(\s*['"]([A-Z][A-Z0-9_]{2,})['"]/gm,
];

function walk(dir, out = []) {
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name)) continue;
      walk(path.join(dir, e.name), out);
    } else if (CODE.test(e.name) && !IS_SPEC.test(e.name)) {
      out.push(path.join(dir, e.name));
    }
  }
  return out;
}

function varsIn(files) {
  const found = new Set();
  for (const file of files) {
    let src;
    try {
      src = fs.readFileSync(file, 'utf8');
    } catch {
      continue;
    }
    for (const re of PATTERNS) {
      re.lastIndex = 0;
      let m;
      while ((m = re.exec(src)) !== null) {
        if (!NOT_A_VAR.has(m[1])) found.add(m[1]);
      }
    }
  }
  return [...found].sort();
}

function main() {
  const check = process.argv.includes('--check');

  // Shared code is compiled into every service, so whatever it reads is
  // needed everywhere.
  const sharedVars = varsIn(walk(LIBS));

  const services = {};
  for (const name of fs.readdirSync(APPS).sort()) {
    const dir = path.join(APPS, name);
    if (!fs.statSync(dir).isDirectory()) continue;
    services[name] = varsIn(walk(dir));
  }

  const previous = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : {};

  const manifest = {
    _README: [
      'Generated by scripts/generate-env-manifest.js. Do not hand-edit "scanned".',
      '',
      'boot-all.js uses this to give each service only the environment it reads,',
      'instead of handing all 39 of them every secret on the platform.',
      '',
      'Add anything the scan cannot see to "extra" for that service: names built',
      'at runtime, or variables read by a dependency rather than by our code.',
      'Entries there are preserved across regeneration and may end with * to',
      'match a prefix, e.g. BANK_ENCRYPTION_KEY*.',
      '',
      'Controlled by ENV_ISOLATION_MODE: off | monitor | enforce. Monitor logs',
      'what would be withheld and changes nothing, which is where this starts.',
    ],
    baseline: previous.baseline ?? [
      // Process plumbing. Without these Node and its children misbehave in
      // ways that are tedious to debug.
      'PATH', 'HOME', 'TMPDIR', 'TMP', 'TEMP', 'TZ', 'LANG', 'LC_ALL',
      'PWD', 'SHELL', 'USER', 'HOSTNAME', 'NODE_ENV', 'NODE_OPTIONS',
      'NODE_EXTRA_CA_CERTS', 'SSL_CERT_FILE', 'npm_*',
      // Set per child by boot-all itself.
      'PORT', 'HOST', 'RABBITMQ_REQUIRED',
      // Shared infrastructure every service connects to. Narrowing these is
      // the per-service database role work (US-3.1), not this change.
      'DATABASE_URL', 'DATABASE_SSL_ENABLED', 'RABBITMQ_URL', 'REDIS_URL',
      'INTERNAL_SERVICE_TOKEN',
      // Token verification: every service validates the caller's JWT.
      'AUTH_JWT_PUBLIC_KEY', 'JWT_SECRET',
    ],
    shared: sharedVars,
    services: {},
  };

  for (const [name, scanned] of Object.entries(services)) {
    const prev = previous.services?.[name] ?? {};
    manifest.services[name] = {
      scanned,
      extra: prev.extra ?? [],
      ...(prev.note ? { note: prev.note } : {}),
    };
  }

  const text = JSON.stringify(manifest, null, 2) + '\n';

  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error(
        'env-manifest.json is out of date. Run: node scripts/generate-env-manifest.js',
      );
      process.exit(1);
    }
    console.log('env-manifest.json is up to date.');
    return;
  }

  fs.writeFileSync(OUT, text);

  const counts = Object.entries(manifest.services)
    .map(([n, v]) => [n, v.scanned.length + v.extra.length])
    .sort((a, b) => a[1] - b[1]);
  console.log(`Wrote ${OUT}`);
  console.log(`${counts.length} services, baseline ${manifest.baseline.length}, shared ${sharedVars.length}`);
  console.log('Fewest variables read:');
  for (const [n, c] of counts.slice(0, 5)) console.log(`  ${String(c).padStart(3)}  ${n}`);
  console.log('Most:');
  for (const [n, c] of counts.slice(-5)) console.log(`  ${String(c).padStart(3)}  ${n}`);
}

main();
