// One-time helper: generates an RSA keypair for local JWT signing and appends
// it to backend/.env in a dotenv-compatible quoted multiline format.
// Run this from inside the backend/ folder: node gen-jwt-keys.js
const { generateKeyPairSync, randomBytes } = require('crypto');
const fs = require('fs');
const path = require('path');

const envPath = path.join(__dirname, '.env');
if (!fs.existsSync(envPath)) {
  console.error('ERROR: .env not found in this folder. Run this from backend/ after copying .env.local.example to .env.');
  process.exit(1);
}

let env = fs.readFileSync(envPath, 'utf8');

if (env.includes('JWT_PRIVATE_KEY=') && !env.includes('JWT_PRIVATE_KEY=\n')) {
  console.log('JWT_PRIVATE_KEY already present in .env — skipping so we don\'t overwrite it.');
} else {
  const { publicKey, privateKey } = generateKeyPairSync('rsa', {
    modulusLength: 2048,
    publicKeyEncoding: { type: 'spki', format: 'pem' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  });

  env += '\n\n# --- Generated by gen-jwt-keys.js ---\n';
  env += `JWT_PRIVATE_KEY="${privateKey.trim()}"\n`;
  env += `JWT_PUBLIC_KEY="${publicKey.trim()}"\n`;
  env += `AUTH_JWT_PRIVATE_KEY="${privateKey.trim()}"\n`;
  env += `AUTH_JWT_PUBLIC_KEY="${publicKey.trim()}"\n`;
  console.log('Generated JWT_PRIVATE_KEY / JWT_PUBLIC_KEY (and AUTH_ variants) and appended to .env');
}

// Also fill in a few other secrets the .env template leaves blank/placeholder,
// only if they're still at their placeholder value.
function setIfPlaceholder(key, placeholder, value) {
  const re = new RegExp(`^${key}=${placeholder}$`, 'm');
  if (re.test(env)) {
    env = env.replace(re, `${key}=${value}`);
    console.log(`Set ${key}`);
  }
}

setIfPlaceholder('BANK_ENCRYPTION_KEY', 'your_64_char_hex_key_here', randomBytes(32).toString('hex'));
setIfPlaceholder('OAUTH_TOKEN_ENCRYPTION_KEY', 'your_64_char_hex_key_here', randomBytes(32).toString('hex'));
setIfPlaceholder('CRYPTO_ADDRESS_ENCRYPTION_KEY', 'your_64_char_hex_key_here', randomBytes(32).toString('hex'));

if (!/^INTERNAL_SERVICE_TOKEN=.+/m.test(env)) {
  env += `INTERNAL_SERVICE_TOKEN=${require('crypto').randomUUID()}\n`;
  console.log('Set INTERNAL_SERVICE_TOKEN');
}
if (!/^JWT_SECRET=.+/m.test(env)) {
  env += `JWT_SECRET=${randomBytes(32).toString('hex')}\n`;
  console.log('Set JWT_SECRET');
}
if (!/^E2EE_SERVER_SECRET=.+/m.test(env)) {
  env += `E2EE_SERVER_SECRET=${randomBytes(32).toString('hex')}\n`;
  console.log('Set E2EE_SERVER_SECRET');
}

fs.writeFileSync(envPath, env);
console.log('Done. backend/.env updated.');
